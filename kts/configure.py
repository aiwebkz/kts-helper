#!/usr/bin/env python3
"""Apply the small, repeatable kts-helper branding overlay to RustDesk 1.5.3."""
import argparse
import base64
import ipaddress
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]


def endpoint(value, label):
    if not isinstance(value, str) or not value or value != value.strip():
        raise ValueError(f"{label}: specify a hostname/IP, optionally with a port")
    host, port = value, None
    if value.startswith("["):
        match = re.fullmatch(r"\[([^]]+)\](?::([0-9]+))?", value)
        if not match:
            raise ValueError(f"{label}: invalid bracketed IPv6 endpoint")
        host, port = match.groups()
        ipaddress.IPv6Address(host)
    else:
        if ":" in value:
            host, port = value.rsplit(":", 1)
            if not port.isdecimal():
                raise ValueError(f"{label}: invalid port")
        if len(host) > 253 or not re.fullmatch(
            r"[A-Za-z0-9](?:[A-Za-z0-9.-]*[A-Za-z0-9])?", host
        ) or any(not part or len(part) > 63 or part.startswith("-") or part.endswith("-")
                 for part in host.split(".")):
            raise ValueError(f"{label}: invalid hostname/IP")
    if port is not None and not 1 <= int(port) <= 65535:
        raise ValueError(f"{label}: port must be 1..65535")
    if host.lower().endswith((".invalid", ".example", ".test")) or host.lower() in (
        "localhost", "example.com", "example.net", "example.org"
    ):
        raise ValueError(f"{label}: replace the example host with your server")
    return value


def validate(config, preview=False):
    if not re.fullmatch(r"[a-z][a-z0-9-]{2,39}", config.get("app_name", "")):
        raise ValueError("app_name must use 3..40 lowercase ASCII letters/digits/hyphens")
    if not re.fullmatch(r"[a-z][a-z0-9]*(?:\.[a-z][a-z0-9]*){2,}", config.get("bundle_id", "")):
        raise ValueError("bundle_id must be a reverse DNS identifier, e.g. org.kts.helper")
    if not re.fullmatch(r"[A-Fa-f0-9]{6}", config.get("accent", "")):
        raise ValueError("accent must be a six-digit RGB hex color")
    if preview:
        return config
    endpoint(config.get("id_server"), "id_server")
    endpoint(config.get("relay_server"), "relay_server")
    try:
        key = base64.b64decode(config.get("public_key", ""), validate=True)
    except (ValueError, TypeError) as error:
        raise ValueError("public_key must be base64 from id_ed25519.pub") from error
    if len(key) != 32:
        raise ValueError("public_key must decode to 32 bytes; use id_ed25519.pub, never the private key")
    return config


def replace(path, old, new):
    path = ROOT / path
    text = path.read_text(encoding="utf-8")
    if old == new or old not in text:
        if new not in text:
            raise ValueError(f"Upstream changed: replacement anchor missing in {path}")
        return
    path.write_text(text.replace(old, new), encoding="utf-8")


def apply(config, preview=False):
    name = config["app_name"]
    # A preview never embeds an unvalidated server or a key supplied by accident.
    server = "unconfigured.invalid:21116" if preview else config["id_server"]
    relay = "unconfigured.invalid:21117" if preview else config["relay_server"]
    key = "" if preview else config["public_key"]
    generated = ROOT / "kts/generated"
    generated.mkdir(parents=True, exist_ok=True)
    lines = ["// Generated by kts/configure.py; edit kts/config.json instead."]
    if preview:
        lines += ['#[cfg(not(debug_assertions))]',
                  'compile_error!("Configure the kts-helper server with python3 kts/configure.py before a release build");']
    for const, value in [("APP_NAME", name), ("ID_SERVER", server),
                         ("RELAY_SERVER", relay), ("PUBLIC_KEY", key)]:
        lines.append(f"const {const}: &str = {json.dumps(value)};")
    (generated / "client.rs").write_text("\n".join(lines) + "\n", encoding="utf-8")
    replace("flutter/macos/Runner/Configs/AppInfo.xcconfig",
            "PRODUCT_NAME = RustDesk", f"PRODUCT_NAME = {name}")
    replace("flutter/macos/Runner/Configs/AppInfo.xcconfig",
            "PRODUCT_BUNDLE_IDENTIFIER = com.carriez.flutterHbb",
            f"PRODUCT_BUNDLE_IDENTIFIER = {config['bundle_id']}")
    replace("flutter/macos/Runner.xcodeproj/project.pbxproj", "RustDesk.app", f"{name}.app")
    replace("flutter/macos/Runner.xcodeproj/xcshareddata/xcschemes/Runner.xcscheme",
            "RustDesk.app", f"{name}.app")
    replace("flutter/macos/Runner.xcodeproj/project.pbxproj",
            "PRODUCT_BUNDLE_IDENTIFIER = com.carriez.rustdesk;",
            f"PRODUCT_BUNDLE_IDENTIFIER = {config['bundle_id']};")
    replace("flutter/macos/Runner.xcodeproj/project.pbxproj",
            "DEVELOPMENT_TEAM = HZF9JMC8YN;", 'DEVELOPMENT_TEAM = "";')
    info = ROOT / "flutter/macos/Runner/Configs/AppInfo.xcconfig"
    if "PRODUCT_MODULE_NAME = RustDesk" not in info.read_text(encoding="utf-8"):
        with info.open("a", encoding="utf-8") as output:
            # XIBs reference Swift classes in this module, independently of the product name.
            output.write("\nPRODUCT_MODULE_NAME = RustDesk\n")
    replace("build.py", "Release/RustDesk.app/Contents/MacOS/", f"Release/{name}.app/Contents/MacOS/")
    replace("flutter/windows/runner/Runner.rc", '"RustDesk Remote Desktop"', f'"{name} Remote Desktop"')
    replace("flutter/windows/runner/Runner.rc", '"ProductName", "RustDesk"', f'"ProductName", "{name}"')
    replace("flutter/windows/runner/Runner.rc", '"InternalName", "rustdesk"', f'"InternalName", "{name}"')
    replace("flutter/windows/runner/Runner.rc", '"OriginalFilename", "rustdesk.exe"', f'"OriginalFilename", "{name}.exe"')
    replace("libs/portable/Cargo.toml", 'ProductName = "RustDesk"', f'ProductName = "{name}"')
    replace("libs/portable/Cargo.toml", 'OriginalFilename = "rustdesk.exe"', f'OriginalFilename = "{name}.exe"')
    replace("libs/portable/Cargo.toml", 'FileDescription = "RustDesk Remote Desktop"', f'FileDescription = "{name} Remote Desktop"')
    # Internal library/protocol names stay upstream-compatible; only product identity changes.
    for before, after in [("0xFF0071FF", "0xFF" + config["accent"].upper()),
                          ("0x770071FF", "0x77" + config["accent"].upper()),
                          ("0xAA0071FF", "0xAA" + config["accent"].upper()),
                          ("0xFF2C8CFF", "0xFF" + config["accent"].upper()),
                          ("0xFF00B6F0", "0xFF" + config["accent"].upper())]:
        replace("flutter/lib/common.dart", before, after)
    replace("flutter/lib/desktop/pages/desktop_home_page.dart", "0xFF2F65BA", "0xFF" + config["accent"].upper())
    print(f"Applied {name}: {'preview; release builds disabled' if preview else server}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=ROOT / "kts/config.json")
    parser.add_argument("--preview", action="store_true", help="Apply branding with networking unconfigured; blocks release builds")
    parser.add_argument("--check", action="store_true", help="Validate without modifying files")
    args = parser.parse_args()
    try:
        config = validate(json.loads(args.config.read_text(encoding="utf-8")), args.preview)
        if args.check:
            print("Configuration valid" + (" (branding preview only)" if args.preview else ""))
        else:
            apply(config, args.preview)
    except (ValueError, OSError, KeyError) as error:
        print(f"Configuration error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
